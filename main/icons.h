#pragma once

#include <stdint.h>
#include <string.h>

// 16x16 1-bpp menu icons, row-major MSB-first (2 bytes/row), for gfx_bitmap().
// Included only by engine.c. Looked up by stable game id so order is irrelevant.

#define ICON_W 16
#define ICON_H 16

// Two paddles + a center ball.
static const uint8_t ICON_PONG[32] = {
    0x00,0x00, 0x00,0x00, 0x00,0x00, 0x00,0x00,
    0x60,0x06, 0x60,0x06, 0x60,0x06, 0x61,0x86,
    0x61,0x86, 0x60,0x06, 0x60,0x06, 0x60,0x06,
    0x00,0x00, 0x00,0x00, 0x00,0x00, 0x00,0x00,
};

// A character flanked by a swarm of dots.
static const uint8_t ICON_SURVIVOR[32] = {
    0x80,0x01, 0x00,0x00, 0x40,0x02, 0x01,0x80,
    0x01,0x80, 0x42,0x42, 0x00,0x00, 0x18,0x18,
    0x18,0x18, 0x00,0x00, 0x42,0x42, 0x01,0x80,
    0x01,0x80, 0x40,0x02, 0x00,0x00, 0x80,0x01,
};

// A downward arrow — descend the well.
static const uint8_t ICON_DESCENDER[32] = {
    0x00,0x00, 0x01,0x80, 0x01,0x80, 0x01,0x80,
    0x01,0x80, 0x01,0x80, 0x01,0x80, 0x7F,0xFE,
    0x3F,0xFC, 0x1F,0xF8, 0x0F,0xF0, 0x07,0xE0,
    0x03,0xC0, 0x01,0x80, 0x00,0x00, 0x00,0x00,
};

// A tetromino stack.
static const uint8_t ICON_PUZZLER[32] = {
    0x00,0x00, 0x0F,0x00, 0x0F,0x00, 0x0F,0x00,
    0x0F,0x00, 0x00,0xF0, 0x00,0xF0, 0x3C,0xF0,
    0x3C,0xF0, 0x3C,0x3C, 0x3C,0x3C, 0xFF,0x3C,
    0xFF,0x3C, 0xFF,0xFF, 0xFF,0xFF, 0x00,0x00,
};

// A speeding car.
static const uint8_t ICON_RUNNER[32] = {
    0x00,0x00, 0x03,0xC0, 0x03,0xC0, 0x07,0xE0,
    0x3F,0xFC, 0x3F,0xFC, 0x3F,0xFC, 0x07,0xE0,
    0x07,0xE0, 0x3F,0xFC, 0x3F,0xFC, 0x3F,0xFC,
    0x07,0xE0, 0x03,0xC0, 0x00,0x00, 0x00,0x00,
};

static inline const uint8_t *icon_for_id(const char *id)
{
    if (strcmp(id, "survivor")  == 0) return ICON_SURVIVOR;
    if (strcmp(id, "descender") == 0) return ICON_DESCENDER;
    if (strcmp(id, "puzzler")   == 0) return ICON_PUZZLER;
    if (strcmp(id, "runner")    == 0) return ICON_RUNNER;
    if (strcmp(id, "pong")      == 0) return ICON_PONG;
    return NULL;
}
