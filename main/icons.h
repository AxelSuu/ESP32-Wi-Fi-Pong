#pragma once

#include <stdint.h>
#include <string.h>

// 16x16 1-bpp menu icons, row-major MSB-first (2 bytes/row), for gfx_bitmap().
// Included only by engine.c. Looked up by stable game id so order is irrelevant.

#define ICON_W 16
#define ICON_H 16

// Two paddles + a center ball.
static const uint8_t ICON_PONG[32] = {
    0x00,0x00, 0x00,0x00, 0x00,0x00, 0x00,0x00,
    0x60,0x06, 0x60,0x06, 0x60,0x06, 0x61,0x86,
    0x61,0x86, 0x60,0x06, 0x60,0x06, 0x60,0x06,
    0x00,0x00, 0x00,0x00, 0x00,0x00, 0x00,0x00,
};

// A winding body with a food pellet.
static const uint8_t ICON_SNAKE[32] = {
    0x00,0x00, 0x7F,0x00, 0x7F,0x00, 0x03,0x00,
    0x03,0x00, 0x1F,0xC0, 0x1F,0xC0, 0x18,0x00,
    0x18,0x00, 0x1F,0xE0, 0x1F,0xE0, 0x00,0x30,
    0x00,0x00, 0x00,0x06, 0x00,0x06, 0x00,0x00,
};

// Top-down car: body + four wheels.
static const uint8_t ICON_RACER[32] = {
    0x00,0x00, 0x03,0xC0, 0x07,0xE0, 0x77,0xFC,
    0x77,0xFC, 0x77,0xFC, 0x07,0xE0, 0x07,0xE0,
    0x07,0xE0, 0x07,0xE0, 0x77,0xFC, 0x77,0xFC,
    0x77,0xFC, 0x07,0xE0, 0x03,0xC0, 0x00,0x00,
};

// Two light-cycle trails meeting.
static const uint8_t ICON_TRON[32] = {
    0x00,0x00, 0x00,0x00, 0x00,0x00, 0x7F,0xE0,
    0x00,0x20, 0x00,0x20, 0x00,0x70, 0x00,0x00,
    0x0E,0x00, 0x04,0x00, 0x04,0x00, 0x04,0x00,
    0x07,0xFE, 0x00,0x00, 0x00,0x00, 0x00,0x00,
};

// A brick wall above a paddle and ball.
static const uint8_t ICON_BREAKOUT[32] = {
    0x00,0x00, 0xFF,0xFE, 0xDB,0x6E, 0xFF,0xFE,
    0x6D,0xB6, 0xFF,0xFE, 0x00,0x00, 0x00,0x00,
    0x00,0x80, 0x01,0x00, 0x00,0x00, 0x00,0x00,
    0x00,0x00, 0x0F,0xF0, 0x00,0x00, 0x00,0x00,
};

static inline const uint8_t *icon_for_id(const char *id)
{
    if (strcmp(id, "pong")     == 0) return ICON_PONG;
    if (strcmp(id, "snake")    == 0) return ICON_SNAKE;
    if (strcmp(id, "racer")    == 0) return ICON_RACER;
    if (strcmp(id, "tron")     == 0) return ICON_TRON;
    if (strcmp(id, "breakout") == 0) return ICON_BREAKOUT;
    return NULL;
}
