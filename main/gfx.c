// --- framebuffer access (for the panel driver + host tests) ---

const uint8_t *gfx_framebuffer(void)  { return s_framebuf; }
int            gfx_framebuffer_size(void) { return FRAMEBUF_SIZE; }

void gfx_set_origin(int dx, int dy) { s_origin_x = dx; s_origin_y = dy; }

// --- pixel write ---
// SSD1327 layout: byte[x/2 + y*64], x-even → high nibble, x-odd → low nibble.

void gfx_pixel(int x, int y, uint8_t nibble)
{
    x += s_origin_x;
    y += s_origin_y;
    if (x < 0 || x >= SCREEN_WIDTH || y < 0 || y >= SCREEN_HEIGHT) return;
    int idx = y * 64 + x / 2;
    nibble &= 0x0F;
    if (x & 1) s_framebuf[idx] = (s_framebuf[idx] & 0xF0) | nibble;
    else       s_framebuf[idx] = (s_framebuf[idx] & 0x0F) | (nibble << 4);
}

uint8_t gfx_get_pixel(int x, int y)
{
    if (x < 0 || x >= SCREEN_WIDTH || y < 0 || y >= SCREEN_HEIGHT) return 0;
    int idx = y * 64 + x / 2;
    return (x & 1) ? (s_framebuf[idx] & 0x0F) : (s_framebuf[idx] >> 4);
}

void gfx_clear(uint8_t nibble)
{
    uint8_t b = ((nibble & 0x0F) << 4) | (nibble & 0x0F);
    memset(s_framebuf, b, FRAMEBUF_SIZE);
}

// --- shapes ---

void gfx_hline(int x, int y, int w, uint8_t shade)
{
    for (int i = 0; i < w; i++) gfx_pixel(x + i, y, shade);
}

void gfx_vline(int x, int y, int h, uint8_t shade)
{
    for (int i = 0; i < h; i++) gfx_pixel(x, y + i, shade);
}

void gfx_rect(int x, int y, int w, int h, uint8_t shade)
{
    for (int row = 0; row < h; row++) gfx_hline(x, y + row, w, shade);
}

void gfx_frame(int x, int y, int w, int h, uint8_t shade)
{
    if (w <= 0 || h <= 0) return;
    gfx_hline(x, y, w, shade);
    gfx_hline(x, y + h - 1, w, shade);
    gfx_vline(x, y, h, shade);
    gfx_vline(x + w - 1, y, h, shade);
}

void gfx_line(int x0, int y0, int x1, int y1, uint8_t shade)
{
    int dx = x1 - x0, dy = y1 - y0;
    int sx = dx < 0 ? -1 : 1, sy = dy < 0 ? -1 : 1;
    dx = dx < 0 ? -dx : dx;
    dy = dy < 0 ? -dy : dy;
    int err = dx - dy;
    for (;;) {
        gfx_pixel(x0, y0, shade);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 <  dx) { err += dx; y0 += sy; }
    }
}

void gfx_circle(int cx, int cy, int r, uint8_t shade)
{
    for (int dy = -r; dy <= r; dy++) {
        int dx = 0;
        while (dx * dx + dy * dy <= r * r) dx++;
        dx--;
        gfx_hline(cx - dx, cy + dy, 2 * dx + 1, shade);
    }
}

// --- text ---

static void draw_glyph(int x, int y, char c, uint8_t shade, int scale)
{
    unsigned char uc = (unsigned char)c;
    if (uc < 0x20 || uc > 0x7F) uc = '?';
    const uint8_t *glyph = font5x7[uc - 0x20];
    for (int col = 0; col < 5; col++) {
        uint8_t line = glyph[col];
        for (int row = 0; row < 7; row++) {
            if (line & (1 << row)) {
                if (scale <= 1) gfx_pixel(x + col, y + row, shade);
                else            gfx_rect(x + col * scale, y + row * scale, scale, scale, shade);
            }
        }
    }
}

void gfx_text(int x, int y, const char *str, uint8_t shade)
{
    while (*str) {
        draw_glyph(x, y, *str++, shade, 1);
        x += 6;
        if (x >= SCREEN_WIDTH) break;
    }
}

void gfx_text_scaled(int x, int y, const char *str, uint8_t shade, int scale)
{
    if (scale < 1) scale = 1;
    while (*str) {
        draw_glyph(x, y, *str++, shade, scale);
        x += 6 * scale;
    }
}

int gfx_text_width(const char *str, int scale)
{
    if (scale < 1) scale = 1;
    return (int)strlen(str) * 6 * scale;
}

void gfx_bitmap(int x, int y, int w, int h, const uint8_t *bits, uint8_t shade)
{
    int stride = (w + 7) / 8;   // bytes per row (rows are byte-aligned)
    for (int row = 0; row < h; row++) {
        for (int col = 0; col < w; col++) {
            uint8_t byte = bits[row * stride + (col >> 3)];
            if (byte & (0x80 >> (col & 7))) gfx_pixel(x + col, y + row, shade);
        }
    }
}
